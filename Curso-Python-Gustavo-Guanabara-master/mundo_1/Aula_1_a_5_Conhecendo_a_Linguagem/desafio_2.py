''' Crie um script Python que leia o dia, 
o mês e o ano de nascimento de uma pessoa 
e mostre uma mensagem com a data formatada
'''
dia = int(input("Digite o dia do seu nascimento: \n"))
mes = str(input("Digite o mes do seu nascimento: \n"))
